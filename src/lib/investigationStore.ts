export function getStoredInvestigations(): InvestigationCase[] {
  if (typeof window === "undefined") return DEFAULT_CASES;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(DEFAULT_CASES));
      return DEFAULT_CASES;
    }
    return JSON.parse(raw);
  } catch (err) {
    console.warn("Failed to read investigations from localStorage:", err);
    return DEFAULT_CASES;
  }
}

export function saveInvestigation(c: InvestigationCase): void {
  if (typeof window === "undefined") return;
  try {
    const cases = getStoredInvestigations();
    const idx = cases.findIndex((item) => item.id === c.id);
    if (idx >= 0) {
      cases[idx] = { ...c, updatedAt: Date.now() };
    } else {
      cases.unshift({ ...c, updatedAt: Date.now() });
    }
    localStorage.setItem(STORAGE_KEY, JSON.stringify(cases));
  } catch (err) {
    console.warn("Failed to persist investigation case:", err);
  }
}

export function deleteInvestigation(id: string): void {
  if (typeof window === "undefined") return;
  try {
    const cases = getStoredInvestigations();
    const filtered = cases.filter((item) => item.id !== id);
    localStorage.setItem(STORAGE_KEY, JSON.stringify(filtered));
  } catch (err) {
    console.warn("Failed to delete investigation case:", err);
  }
}

export function exportInvestigationMarkdown(c: InvestigationCase): string {
  const dateStr = new Date(c.createdAt).toUTCString();
  return `# MARITIME INVESTIGATION DOSSIER: ${c.title.toUpperCase()}
**Case ID:** ${c.id}  
**Target:** ${c.targetName} (${c.targetType})  
**Status:** ${c.status}  
**Lead Analyst:** ${c.leadAnalyst}  
**Report Date:** ${dateStr}  

---

## 1. Executive Summary
${c.summary}

## 2. Investigation Time Window
- **Start:** ${new Date(c.timeWindowStart).toUTCString()}
- **End:** ${new Date(c.timeWindowEnd).toUTCString()}

## 3. Evidence & Findings
${c.findings
  .map(
    (f, i) =>
      `### ${i + 1}. [${f.type}] ${f.statement}
- **Supporting Evidence:** ${f.evidenceRef || "Recorded telemetry fix"}`,
  )
  .join("\n\n")}

---
*Generated by Global Maritime Port Monitor — TIME MACHINE Intelligence System*
`;
}
